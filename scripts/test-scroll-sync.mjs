import assert from 'node:assert/strict'
import test from 'node:test'

import {
  editorLineAnchors,
  mapAnchoredScrollTop,
  maximumScrollAnchors,
  sampleAnchorIndices,
  ScrollSyncController,
  sourceLineFromAnchors,
} from '../frontend/src/scroll-sync.ts'

function viewport(scrollTop, scrollHeight, clientHeight = 200) {
  return { scrollTop, scrollHeight, clientHeight }
}

test('editor drives preview proportionally without feedback', () => {
  const controller = new ScrollSyncController()
  const editor = viewport(400, 1000)
  const preview = viewport(0, 1800)

  controller.begin('editor')
  assert.equal(controller.sync('editor', editor, preview), true)
  assert.equal(preview.scrollTop, 800)

  // The preview scroll event generated by the assignment above is ignored.
  assert.equal(controller.sync('preview', preview, editor), false)
  assert.equal(editor.scrollTop, 400)
})

test('preview takes control after explicit user intent', () => {
  const controller = new ScrollSyncController()
  const editor = viewport(200, 1000)
  const preview = viewport(1200, 1800)

  controller.begin('preview')
  assert.equal(controller.sync('preview', preview, editor), true)
  assert.equal(editor.scrollTop, 600)

  assert.equal(controller.sync('editor', editor, preview), false)
  assert.equal(preview.scrollTop, 1200)
})

test('idle and inactive-pane reflow never move the opposite pane', () => {
  const controller = new ScrollSyncController()
  const editor = viewport(350, 1000)
  const preview = viewport(700, 1800)

  // No wheel, pointer or keyboard intent: an idle scroll event is ignored.
  assert.equal(controller.sync('preview', preview, editor), false)
  assert.equal(editor.scrollTop, 350)

  controller.begin('editor')
  preview.scrollHeight = 2400
  preview.scrollTop = 760
  assert.equal(controller.sync('preview', preview, editor), false)
  assert.equal(editor.scrollTop, 350)
})

test('scroll ratio is clamped at both ends', () => {
  const controller = new ScrollSyncController()
  const editor = viewport(9999, 1000)
  const preview = viewport(0, 1800)

  controller.begin('editor')
  controller.sync('editor', editor, preview)
  assert.equal(preview.scrollTop, 1600)

  editor.scrollTop = -20
  controller.sync('editor', editor, preview)
  assert.equal(preview.scrollTop, 0)
})

test('source-line anchors align semantic sections across tall diagrams', () => {
  const mapping = {
    maxLine: 362,
    sourceAnchors: [
      { line: 0, top: 0 },
      { line: 280, top: 520 },
      { line: 330, top: 700 },
    ],
    targetAnchors: [
      { line: 0, top: 0 },
      { line: 280, top: 1800 },
      { line: 330, top: 2800 },
    ],
  }

  assert.equal(mapAnchoredScrollTop(700, 800, 4000, mapping), 2800)
  assert.equal(mapAnchoredScrollTop(2800, 4000, 800, {
    ...mapping,
    sourceAnchors: mapping.targetAnchors,
    targetAnchors: mapping.sourceAnchors,
  }), 700)
})

test('render reconciliation restores the active editor after asynchronous preview reflow', () => {
  const controller = new ScrollSyncController()
  const editor = viewport(800, 1000)
  const preview = viewport(600, 2400)

  controller.begin('editor')
  assert.equal(controller.sync('editor', editor, preview, {
    maxLine: 100,
    sourceAnchors: [],
    targetAnchors: [],
  }), true)
  assert.equal(preview.scrollTop, 2200)

  // Mermaid, an image, or a font finishes after the first paint. The preview
  // range and semantic anchors move, but the editor remains the source of truth.
  preview.scrollHeight = 3400
  assert.equal(controller.sync('editor', editor, preview, {
    maxLine: 100,
    sourceAnchors: [{ line: 80, top: 800 }],
    targetAnchors: [{ line: 80, top: 2700 }],
  }), true)
  assert.equal(preview.scrollTop, 2700)

  preview.scrollTop = 900
  controller.begin('preview')
  editor.scrollTop = 640
  assert.equal(controller.sync('editor', editor, preview), false)
  assert.equal(preview.scrollTop, 900)
})

test('semantic anchor sampling is bounded', () => {
  const indices = sampleAnchorIndices(1_000_000)
  assert.equal(indices.length, maximumScrollAnchors)
  assert.equal(indices[0], 0)
  assert.equal(indices.at(-1), 999_999)
  assert.equal(new Set(indices).size, maximumScrollAnchors)

})

test('large no-wrap editors derive exact line anchors without a document-size cutoff', () => {
  const anchors = editorLineAnchors([0, 51, 923, 1_253, 11_849], 24.08, 24)
  assert.deepEqual(anchors, [
    { line: 0, top: 24 },
    { line: 51, top: 1_252.08 },
    { line: 923, top: 22_249.84 },
    { line: 1_253, top: 30_196.239999999998 },
    { line: 11_849, top: 285_347.92 },
  ])
  assert.deepEqual(editorLineAnchors([3, 3, -1, Number.NaN, 1], 20, 12), [
    { line: 1, top: 32 },
    { line: 3, top: 72 },
  ])
  assert.deepEqual(editorLineAnchors([1], 0, 12), [])
  assert.equal(editorLineAnchors(Array.from({ length: 10_000 }, (_, line) => line), 20, 0).length, maximumScrollAnchors)
})

test('wrapped editors use measured geometry while no-wrap editors retain analytical anchors', async () => {
  const { readFile } = await import('node:fs/promises')
  const app = await readFile(new URL('../frontend/src/App.vue', import.meta.url), 'utf8')
  assert.match(app, /function measureEditorScrollAnchors[\s\S]*editorLineAnchors\([\s\S]*computed\.lineHeight[\s\S]*computed\.paddingTop/)
  assert.match(app, /if \(wordWrapEnabled\.value\) return measureWrappedEditorScrollAnchors\(lines\)/)
  assert.match(app, /function measureWrappedEditorScrollAnchors[\s\S]*document\.createRange\(\)/)
  assert.match(app, /sourceHeadingModel\.value\.headings/)
})

test('measured wrapped anchors drive sticky heading line selection', () => {
  const anchors = [
    { line: 0, top: 24 },
    { line: 8, top: 216 },
    { line: 20, top: 696 },
  ]
  assert.equal(sourceLineFromAnchors(anchors, 24, 20), 0)
  assert.equal(sourceLineFromAnchors(anchors, 336, 20), 11)
  assert.equal(sourceLineFromAnchors(anchors, 1000, 20), 20)
})
